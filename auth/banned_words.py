def filter_text(text: str) -> str:
    """命中敏感词替换为等长 *，返回处理后的文本。词表小（数百词），线性扫描即可。"""
    if not text:
        return text
    hit = [w for w in BANNED_WORDS if w.strip() and w in text]
    for w in hit:
        text = text.replace(w, "*" * len(w))
    return text
